import contextlib
import importlib.util
import io
from pathlib import Path
import sys
import tempfile
import unittest
from unittest.mock import patch


spec = importlib.util.spec_from_file_location(
    "checker", Path(__file__).with_name("check-winget-manifest.py"))
checker = importlib.util.module_from_spec(spec)
spec.loader.exec_module(checker)

TAG = "v1.2.3"
VERSION = "1.2.3"
AMD64 = f"what-to-run_{VERSION}_windows_amd64.zip"
ARM64 = f"what-to-run_{VERSION}_windows_arm64.zip"
HASHES = {AMD64: "a" * 64, ARM64: "b" * 64}


def download_url(name):
    return f"https://github.com/zanza00/what-to-run/releases/download/{TAG}/{name}"


def version_manifest(version=VERSION):
    return f"""\
# This file was generated by GoReleaser. DO NOT EDIT.
PackageIdentifier: zanza00.WhatToRun
PackageVersion: {version}
DefaultLocale: en-US
ManifestType: version
ManifestVersion: 1.12.0
"""


def installer_manifest(version=VERSION, nested="portable", path="wtr.exe",
                       alias="wtr", installers=None):
    if installers is None:
        installers = f"""\
  - Architecture: x64
    NestedInstallerType: {nested}
    NestedInstallerFiles:
      - RelativeFilePath: {path}
        PortableCommandAlias: {alias}
    InstallerUrl: {download_url(AMD64)}
    InstallerSha256: {HASHES[AMD64]}
    UpgradeBehavior: uninstallPrevious
  - Architecture: arm64
    NestedInstallerType: {nested}
    NestedInstallerFiles:
      - RelativeFilePath: {path}
        PortableCommandAlias: {alias}
    InstallerUrl: {download_url(ARM64)}
    InstallerSha256: {HASHES[ARM64]}
    UpgradeBehavior: uninstallPrevious
"""
    return f"""\
# This file was generated by GoReleaser. DO NOT EDIT.
PackageIdentifier: zanza00.WhatToRun
PackageVersion: {version}
InstallerLocale: en-US
InstallerType: zip
ReleaseDate: "2026-10-25"
Installers:
{installers}ManifestType: installer
ManifestVersion: 1.12.0
"""


def locale_manifest(version=VERSION):
    return f"""\
# This file was generated by GoReleaser. DO NOT EDIT.
PackageIdentifier: zanza00.WhatToRun
PackageVersion: {version}
PackageLocale: en-US
Publisher: zanza00
PackageName: What to Run
Description: |-
  Runs the task you pick from a filterable list: no file to open first.
Moniker: wtr
ManifestType: defaultLocale
ManifestVersion: 1.12.0
"""


def manifests():
    return {
        "version": version_manifest(),
        "installer": installer_manifest(),
        "locale": locale_manifest(),
    }


def checksums(sums):
    return "\n".join(f"{digest}  {name}" for name, digest in sums.items()) + "\n"


class CheckTest(unittest.TestCase):
    def setUp(self):
        self.manifests = manifests()
        self.sums = dict(HASHES)

    def problems(self):
        return checker.check(TAG, self.manifests, self.sums)

    def test_valid_manifest_has_no_problems(self):
        self.assertEqual(self.problems(), [])

    def test_handwritten_manifest_is_accepted(self):
        # The first package was written by hand: no indentation under
        # `Installers:` and one NestedInstallerType for the whole list.
        installers = f"""\
- Architecture: x64
  NestedInstallerFiles:
  - RelativeFilePath: wtr.exe
    PortableCommandAlias: wtr
  InstallerUrl: {download_url(AMD64)}
  InstallerSha256: {HASHES[AMD64].upper()}
- Architecture: arm64
  NestedInstallerFiles:
  - RelativeFilePath: wtr.exe
    PortableCommandAlias: wtr
  InstallerUrl: {download_url(ARM64)}
  InstallerSha256: {HASHES[ARM64].upper()}
"""
        self.manifests["installer"] = installer_manifest(
            installers=installers).replace(
                "InstallerType: zip",
                "InstallerType: zip\nNestedInstallerType: portable")
        self.assertEqual(self.problems(), [])

    def test_wrong_version_is_reported(self):
        self.manifests["installer"] = installer_manifest(version="9.9.9")
        self.assertIn(
            "installer manifest carries version '9.9.9', expected '1.2.3'",
            self.problems())

    def test_wrong_identifier_is_reported(self):
        self.manifests["locale"] = locale_manifest().replace(
            "zanza00.WhatToRun", "zanza00.Other")
        self.assertIn(
            "locale manifest is for 'zanza00.Other', expected 'zanza00.WhatToRun'",
            self.problems())

    def test_wrong_installer_type_is_reported(self):
        self.manifests["installer"] = installer_manifest().replace(
            "InstallerType: zip", "InstallerType: msix")
        self.assertIn(
            "installer manifest has InstallerType 'msix', expected 'zip'",
            self.problems())

    def test_wrong_nested_installer_type_is_reported(self):
        self.manifests["installer"] = installer_manifest(nested="msix")
        self.assertIn(
            "x64 installer type is 'msix', expected 'portable'",
            self.problems())

    def test_wrong_url_is_reported(self):
        self.manifests["installer"] = installer_manifest().replace(
            download_url(ARM64), download_url(AMD64))
        self.assertIn(
            f"arm64 downloads {download_url(AMD64)!r}, "
            f"expected {download_url(ARM64)!r}",
            self.problems())

    def test_wrong_hash_is_reported(self):
        self.manifests["installer"] = installer_manifest().replace(
            HASHES[AMD64], "d" * 64)
        self.assertIn(
            f"x64 hash does not match checksums.txt for {AMD64}",
            self.problems())

    def test_missing_checksum_is_reported(self):
        del self.sums[ARM64]
        self.assertIn(f"checksums.txt has no {ARM64}", self.problems())

    def test_wrong_command_alias_is_reported(self):
        self.manifests["installer"] = installer_manifest(alias="what-to-run")
        self.assertIn(
            "arm64 alias is 'what-to-run', expected 'wtr'", self.problems())

    def test_wrong_relative_path_is_reported(self):
        self.manifests["installer"] = installer_manifest(path="bin/wtr.exe")
        self.assertIn(
            "x64 installs 'bin/wtr.exe', expected 'wtr.exe'", self.problems())

    def test_missing_architecture_is_reported(self):
        self.manifests["installer"] = installer_manifest(installers="""\
  - Architecture: x64
    NestedInstallerType: portable
    NestedInstallerFiles:
      - RelativeFilePath: wtr.exe
        PortableCommandAlias: wtr
    InstallerUrl: %s
    InstallerSha256: %s
""" % (download_url(AMD64), HASHES[AMD64]))
        self.assertIn("manifest has no arm64 installer", self.problems())

    def test_unexpected_architecture_is_reported(self):
        self.manifests["installer"] = installer_manifest().replace(
            "ManifestType: installer",
            "  - Architecture: x86\n"
            "    NestedInstallerType: portable\n"
            "    NestedInstallerFiles:\n"
            "      - RelativeFilePath: wtr.exe\n"
            "        PortableCommandAlias: wtr\n"
            "    InstallerUrl: https://example.com/what-to-run_windows_386.zip\n"
            f"    InstallerSha256: {'c' * 64}\n"
            "ManifestType: installer",
        )
        self.assertIn(
            "manifest carries an unexpected x86 installer", self.problems())

    def test_unstable_tag_is_rejected(self):
        with self.assertRaises(ValueError):
            checker.check("0.8.0-SNAPSHOT-4a618f0", self.manifests, self.sums)


class MainTest(unittest.TestCase):
    def setUp(self):
        directory = tempfile.TemporaryDirectory()
        self.addCleanup(directory.cleanup)
        self.directory = Path(directory.name)

    def run_main(self, manifests, checksums_text):
        for name, filename in checker.FILES.items():
            path = self.directory / filename
            if name in manifests:
                path.write_text(manifests[name])
            else:
                path.unlink(missing_ok=True)
        checksums_path = self.directory / "checksums.txt"
        checksums_path.write_text(checksums_text)
        stdout, stderr = io.StringIO(), io.StringIO()
        argv = ["check-winget-manifest.py", TAG, str(self.directory),
                str(checksums_path)]
        with patch.object(sys, "argv", argv), \
                contextlib.redirect_stdout(stdout), \
                contextlib.redirect_stderr(stderr):
            status = checker.main()
        return status, stdout.getvalue(), stderr.getvalue()

    def test_a_matching_manifest_passes(self):
        status, stdout, stderr = self.run_main(manifests(), checksums(HASHES))
        self.assertEqual((status, stderr), (0, ""))
        self.assertIn(f"WinGet manifest for {TAG} matches the release", stdout)

    def test_every_problem_is_printed(self):
        broken = manifests()
        broken["version"] = version_manifest(version="9.9.9")
        broken["installer"] = installer_manifest().replace(
            HASHES[ARM64], "d" * 64)
        status, _, stderr = self.run_main(broken, checksums(HASHES))
        self.assertEqual(status, 1)
        self.assertIn("expected '1.2.3'", stderr)
        self.assertIn("arm64 hash does not match checksums.txt", stderr)

    def test_missing_manifest_fails_with_a_message(self):
        for name in checker.FILES:
            with self.subTest(missing=name):
                broken = manifests()
                del broken[name]
                status, _, stderr = self.run_main(broken, checksums(HASHES))
                self.assertEqual(status, 1)
                self.assertIn("No such file", stderr)


if __name__ == "__main__":
    unittest.main()
